"""
Конфигурация бота: чтение токена группы и настроек из файла .env
через python-dotenv.
"""

import os

from dotenv import load_dotenv

# Загружаем переменные окружения из файла .env (лежит рядом с bot.py)
load_dotenv()

# Токен доступа сообщества
# (Управление сообществом -> Работа с API -> Токен доступа)
TOKEN = os.environ["BOT_TOKEN"]

# Идентификатор (ID) группы ВКонтакте
# (Управление сообществом -> Работа с API -> Версия и идентификатор)
GROUP_ID = int(os.getenv("GROUP_ID", "0"))

# Телефон менеджера клининг-центра для раздела «Связаться с менеджером»
MANAGER_PHONE = os.getenv("MANAGER_PHONE", "+7 (900) 123-45-67")
